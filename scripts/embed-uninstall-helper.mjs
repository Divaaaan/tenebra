import fs from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const sourcePath = new URL('../ui-desktop/src-tauri/installer-release-protection.ps1', import.meta.url);
export const outputPath = new URL('../ui-desktop/src-tauri/installer-release-protection.nsh', import.meta.url);

function nsisString(text) {
  return text.replaceAll('$', () => '$$').replaceAll('"', '$\\"');
}

export function renderUninstallHelper(source) {
  const encoded = Buffer.from(source.replaceAll('\r\n', '\n'), 'utf16le').toString('base64');
  const chunks = encoded.match(/.{1,512}/g);
  const names = chunks.map((_, index) => `TENEBRA_RELEASE_PS${index}`);
  const set = (name, value) => [
    `  StrCpy $0 "${value}"`,
    `  System::Call 'kernel32::SetEnvironmentVariableW(w "${name}", w r0) i.r0'`,
    '  ${If} $0 = 0',
    "    System::Call 'kernel32::GetLastError() i.r0'",
    '    !insertmacro TenebraServiceFailure "prepare protection cleanup for"',
    '  ${EndIf}',
  ];
  const driver = `$s=(0..${chunks.length - 1}|ForEach-Object{[Environment]::GetEnvironmentVariable('TENEBRA_RELEASE_PS'+$_)})-join'';& ([ScriptBlock]::Create([Text.Encoding]::Unicode.GetString([Convert]::FromBase64String($s))))`;
  const execute = '  nsExec::ExecToLog /TIMEOUT=35000 ' + '`"$SYSDIR\\WindowsPowerShell\\v1.0\\powershell.exe" -NoProfile -NonInteractive -Command "' + nsisString(driver) + '"`';
  return [
    '; Generated by scripts/embed-uninstall-helper.mjs. Edit the .ps1 source.',
    '; Constant chunks avoid NSIS string limits and execution of a user-writable script.',
    '!macro TenebraReleaseHostProtection',
    ...set('TENEBRA_RELEASE_CORE', '$INSTDIR\\tenebra-core.exe'),
    ...chunks.flatMap((chunk, index) => set(names[index], chunk)),
    execute,
    '  Pop $0',
    '  Push $0',
    ...['TENEBRA_RELEASE_CORE', ...names].map(name => `  System::Call 'kernel32::SetEnvironmentVariableW(w "${name}", p 0) i.r0'`),
    '  Pop $0',
    '  !insertmacro TenebraRequireSuccess "release owned host protection before unregistering"',
    '!macroend',
    '',
  ].join('\n');
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const output = renderUninstallHelper(fs.readFileSync(sourcePath, 'utf8'));
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(outputPath, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error('Run node scripts/embed-uninstall-helper.mjs');
  } else fs.writeFileSync(outputPath, output);
  console.log(fileURLToPath(outputPath));
}
